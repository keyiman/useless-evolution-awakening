import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-gpu-sandbox'] });
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await p.goto('http://127.0.0.1:5174/?tree=1', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(3500);
console.log('legacy topbar:', await p.locator('.topbar').count(), 'brand:', await p.locator('.brand-text').innerText().catch(()=>''));
await p.goto('http://127.0.0.1:5174/', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(5000);
await p.locator('.base-card', { hasText: '椅子' }).click();
await p.waitForTimeout(6000);
console.log('chair base:', await p.locator('.base-card.on strong').innerText());
const before = await p.locator('.organ-card.on').count();
await p.locator('button', { hasText: '让它自己变异' }).click();
await p.waitForTimeout(6500);
const after = await p.locator('.organ-card.on').count();
console.log('auto organs before/after:', before, after);
await p.screenshot({ path: '_research/lab-chair.png' });
console.log('errors:', JSON.stringify(errs.slice(0, 6)));
await b.close();
