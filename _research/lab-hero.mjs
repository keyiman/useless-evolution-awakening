import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-gpu-sandbox'] });
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://127.0.0.1:5174/', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(5000);
for (const name of ['轮式底盘','防护笼']) await p.locator('.organ-card', { hasText: name }).click();
await p.waitForTimeout(6000);
await p.screenshot({ path: '_research/lab-hero.png' });
console.log('on', await p.locator('.organ-card.on').count(), 'errs', errs.slice(0,3));
console.log('score', await p.locator('.lab-score').innerText());
await b.close();
