import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-gpu-sandbox'] });
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0,120)); });
await p.goto('http://127.0.0.1:5174/?r=qa-final', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(7000);
console.log('cards', await p.locator('.organ-card').count(), 'pending', await p.locator('.organ-card.pending').count());
const click = async (name) => { const c = p.locator('.organ-card', { hasText: name }); await c.scrollIntoViewIfNeeded(); await c.click(); };
await click('轮式底盘'); await p.waitForTimeout(1200);
await click('防护笼'); await p.waitForTimeout(1200);
console.log('score', (await p.locator('.lab-score').innerText()).replace(/\n/g,' '));
await p.locator('button', { hasText: '运行无用性测试' }).click();
await p.waitForTimeout(1600);
console.log('verdict', (await p.locator('.test-verdict').innerText()).replace(/\n/g,' '));
console.log('trigger', (await p.locator('.test-trigger').innerText()).replace(/\n/g,' '));
await p.locator('button', { hasText: '返回观察' }).click();
await p.waitForTimeout(500);
await p.locator('.fusion-chip', { hasText: '椅子' }).click();
await p.waitForTimeout(1500);
console.log('fusion score', (await p.locator('.lab-score').innerText()).replace(/\n/g,' '));
await p.locator('.fusion-chip', { hasText: '不融合' }).click();
await p.locator('button', { hasText: '让它自己变异' }).click();
await p.waitForTimeout(6200);
console.log('auto note', (await p.locator('.lab-note').innerText().catch(()=> '')).replace(/\n/g,' '));
console.log('toast/notes', await p.locator('.lab-toast').count());
console.log('errors', errs.slice(0,3));
await b.close();
